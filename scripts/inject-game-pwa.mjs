/**
 * Adds per-game Add-to-Home-Screen + offline files to every Godot HTML5 export.
 * Idempotent. Safe to re-run after a Godot re-export.
 *
 * Usage:
 *   node scripts/inject-game-pwa.mjs
 *   node scripts/inject-game-pwa.mjs path/to/games
 */
import { createHash } from 'node:crypto';
import { copyFile, readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const bootSrc = path.join(__dirname, 'game-pwa', 'pwa-boot.js');

export function parseGodotExecutable(html) {
  const match = html.match(/"executable"\s*:\s*"([^"]+)"/);
  return match ? match[1] : 'index';
}

export function parseGodotTitle(html, fallback) {
  const match = html.match(/<title>([^<]+)<\/title>/i);
  const title = match ? match[1].trim() : '';
  return title || fallback;
}

export function parseGodotFileSizes(html) {
  const match = html.match(/"fileSizes"\s*:\s*(\{[^}]*\})/);
  if (!match) {
    return {};
  }
  try {
    return JSON.parse(match[1]);
  } catch {
    return {};
  }
}

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function upsertBlock(html, start, end, inner) {
  const block = `${start}\n${inner}\n${end}`;
  if (html.includes(start) && html.includes(end)) {
    return html.replace(new RegExp(`${escapeRegExp(start)}[\\s\\S]*?${escapeRegExp(end)}`), block);
  }
  return html;
}

/** Early inline script so Godot sees parent gamepads after hub fullscreen. */
export function gamepadFocusSnippet() {
  return `<script>
(function () {
  if (window.__CDD_GAMEPAD_FOCUS__) {
    return;
  }
  window.__CDD_GAMEPAD_FOCUS__ = true;
  function focusCanvas() {
    var canvas = document.getElementById('canvas') || document.querySelector('canvas');
    if (canvas) {
      if (!canvas.hasAttribute('tabindex')) {
        canvas.setAttribute('tabindex', '0');
      }
      try {
        canvas.focus({ preventScroll: true });
      } catch (err) {
        canvas.focus();
      }
    }
    try {
      window.focus();
    } catch (err) {}
  }
  try {
    if (window.parent && window.parent !== window && window.parent.navigator && window.parent.navigator.getGamepads && navigator.getGamepads) {
      var localGet = navigator.getGamepads.bind(navigator);
      var parentGet = window.parent.navigator.getGamepads.bind(window.parent.navigator);
      navigator.getGamepads = function () {
        var pads = localGet();
        for (var i = 0; i < pads.length; i++) {
          if (pads[i]) {
            return pads;
          }
        }
        return parentGet();
      };
    }
  } catch (err) {}
  window.addEventListener('message', function (event) {
    if (event && event.data && event.data.type === 'cdd-game-focus') {
      focusCanvas();
    }
  });
  document.addEventListener('fullscreenchange', focusCanvas);
  document.addEventListener('webkitfullscreenchange', focusCanvas);
  window.addEventListener('gamepadconnected', focusCanvas);
})();
</script>`;
}

function shortName(title) {
  const trimmed = title.trim();
  if (trimmed.length <= 12) {
    return trimmed;
  }
  const parts = trimmed.split(/\s+/).filter(Boolean);
  const last = parts[parts.length - 1] || trimmed;
  if (last.length <= 12) {
    return last;
  }
  return trimmed.slice(0, 12).trim();
}

function serviceWorkerSource(cacheName, assets) {
  const list = JSON.stringify(assets, null, 2);
  return `/* Auto-generated by scripts/inject-game-pwa.mjs — do not edit by hand. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const ASSETS = ${list};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await Promise.all(ASSETS.map(async (url) => {
      if (await cache.match(url)) {
        return;
      }
      try {
        const res = await fetch(url, { cache: 'reload' });
        if (res.ok) {
          await cache.put(url, res);
        }
      } catch (err) {
        console.warn('[cdd-offline-sw] skip', url, err);
      }
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys
        .filter((key) => key.startsWith('cdd-offline-') && key !== CACHE_NAME)
        .map((key) => caches.delete(key)),
    );
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') {
    return;
  }
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) {
    return;
  }
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    if (!req.headers.has('Range')) {
      const cached = await cache.match(req, { ignoreSearch: true });
      if (cached) {
        return cached;
      }
    }
    try {
      const res = await fetch(req);
      if (res.ok && !req.headers.has('Range')) {
        cache.put(req, res.clone());
      }
      return res;
    } catch (err) {
      const fallback = await cache.match(req, { ignoreSearch: true });
      if (fallback) {
        return fallback;
      }
      if (req.mode === 'navigate') {
        const page = await cache.match('./index.html') || await cache.match('index.html');
        if (page) {
          return page;
        }
      }
      throw err;
    }
  })());
});
`;
}

async function listCacheAssets(gameDir, exec) {
  const candidates = [
    'index.html',
    `${exec}.js`,
    `${exec}.wasm`,
    `${exec}.pck`,
    `${exec}.png`,
    `${exec}.icon.png`,
    `${exec}.apple-touch-icon.png`,
    `${exec}.audio.worklet.js`,
    `${exec}.audio.position.worklet.js`,
    'cover.png',
    'manifest.json',
    'pwa-boot.js',
    'offline-cache.json',
  ];
  const assets = [];
  for (const name of candidates) {
    if (existsSync(path.join(gameDir, name))) {
      assets.push(name);
    }
  }
  // Always include generated names even before they exist on disk this pass.
  for (const required of ['index.html', 'manifest.json', 'pwa-boot.js', 'offline-cache.json']) {
    if (!assets.includes(required)) {
      assets.push(required);
    }
  }
  return assets;
}

async function fileBytes(filePath) {
  try {
    const s = await stat(filePath);
    return s.size;
  } catch {
    return 0;
  }
}

export async function injectGamePwa(gamesDir) {
  if (!existsSync(gamesDir)) {
    console.warn('inject-game-pwa: missing', gamesDir);
    return [];
  }
  if (!existsSync(bootSrc)) {
    throw new Error('inject-game-pwa: missing ' + bootSrc);
  }

  // Allow `node scripts/inject-game-pwa.mjs games/novadrop` (one folder, not the parent).
  let entries;
  if (existsSync(path.join(gamesDir, 'index.html'))) {
    entries = [{ name: path.basename(gamesDir), isDirectory: () => true }];
    gamesDir = path.dirname(gamesDir);
  } else {
    entries = await readdir(gamesDir, { withFileTypes: true });
  }
  const injected = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }
    const gameDir = path.join(gamesDir, entry.name);
    const indexPath = path.join(gameDir, 'index.html');
    if (!existsSync(indexPath)) {
      continue;
    }
    let html = await readFile(indexPath, 'utf8');
    if (!html.includes('GODOT_CONFIG') && !html.includes('new Engine')) {
      continue;
    }

    const exec = parseGodotExecutable(html);
    const title = parseGodotTitle(html, entry.name);
    const godotSizes = parseGodotFileSizes(html);
    const icon = existsSync(path.join(gameDir, `${exec}.apple-touch-icon.png`))
      ? `${exec}.apple-touch-icon.png`
      : existsSync(path.join(gameDir, `${exec}.icon.png`))
        ? `${exec}.icon.png`
        : 'cover.png';

    await copyFile(bootSrc, path.join(gameDir, 'pwa-boot.js'));

    const assets = await listCacheAssets(gameDir, exec);
    const sizes = { ...godotSizes };
    for (const name of assets) {
      if (!sizes[name]) {
        sizes[name] = await fileBytes(path.join(gameDir, name));
      }
    }
    const version = createHash('sha1')
      .update(
        JSON.stringify({
          exec,
          wasm: sizes[`${exec}.wasm`] || 0,
          pck: sizes[`${exec}.pck`] || 0,
          js: sizes[`${exec}.js`] || 0,
          title,
        }),
      )
      .digest('hex')
      .slice(0, 10);
    const cacheName = `cdd-offline-${entry.name}-${version}`;

    const manifest = {
      id: `./${entry.name}`,
      name: title,
      short_name: shortName(title),
      description: `${title} — play offline from your Home Screen.`,
      start_url: './index.html',
      scope: './',
      display: 'standalone',
      orientation: 'any',
      background_color: '#000000',
      theme_color: '#0d111a',
      icons: icon
        ? [
            {
              src: icon,
              sizes: '180x180',
              type: 'image/png',
              purpose: 'any',
            },
          ]
        : [],
    };

    const cacheInfo = {
      cacheName,
      title,
      assets,
      sizes,
      bytes: Object.values(sizes).reduce((sum, n) => sum + Number(n || 0), 0),
    };

    await writeFile(path.join(gameDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
    await writeFile(path.join(gameDir, 'offline-cache.json'), JSON.stringify(cacheInfo, null, 2) + '\n');
    await writeFile(path.join(gameDir, 'offline-sw.js'), serviceWorkerSource(cacheName, assets));

    const headInner = [
      `<link rel="manifest" href="manifest.json" />`,
      `<meta name="apple-mobile-web-app-capable" content="yes" />`,
      `<meta name="mobile-web-app-capable" content="yes" />`,
      `<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />`,
      `<meta name="apple-mobile-web-app-title" content="${shortName(title).replace(/"/g, '')}" />`,
      `<meta name="theme-color" content="#0d111a" />`,
    ].join('\n');

    if (html.includes('<!-- CDD-PWA -->')) {
      html = upsertBlock(html, '<!-- CDD-PWA -->', '<!-- /CDD-PWA -->', headInner);
    } else {
      html = html.replace('</head>', `<!-- CDD-PWA -->\n${headInner}\n<!-- /CDD-PWA -->\n</head>`);
    }

    const gamepadInner = gamepadFocusSnippet();
    if (html.includes('<!-- CDD-GAMEPAD -->')) {
      html = upsertBlock(html, '<!-- CDD-GAMEPAD -->', '<!-- /CDD-GAMEPAD -->', gamepadInner);
    } else {
      html = html.replace(
        /<body([^>]*)>/i,
        (open) => `${open}\n<!-- CDD-GAMEPAD -->\n${gamepadInner}\n<!-- /CDD-GAMEPAD -->`,
      );
    }

    const bootInner = `<script src="pwa-boot.js" defer></script>`;
    if (html.includes('<!-- CDD-PWA-BOOT -->')) {
      html = upsertBlock(html, '<!-- CDD-PWA-BOOT -->', '<!-- /CDD-PWA-BOOT -->', bootInner);
    } else {
      html = html.replace('</body>', `<!-- CDD-PWA-BOOT -->\n${bootInner}\n<!-- /CDD-PWA-BOOT -->\n</body>`);
    }

    html = html.replace(
      /<meta name="viewport" content="width=device-width, user-scalable=no, initial-scale=1.0">/,
      '<meta name="viewport" content="width=device-width, user-scalable=no, initial-scale=1.0, viewport-fit=cover">',
    );

    await writeFile(indexPath, html);
    injected.push(entry.name);
    console.log(`inject-game-pwa: ${entry.name} (${title}, ${assets.length} files)`);
  }

  return injected;
}

function isDirectRun() {
  try {
    return pathToFileURL(process.argv[1]).href === import.meta.url;
  } catch {
    return false;
  }
}

if (isDirectRun()) {
  const target = process.argv[2]
    ? path.resolve(process.argv[2])
    : path.join(root, 'games');
  const injected = await injectGamePwa(target);
  if (!injected.length) {
    console.warn('inject-game-pwa: no Godot game folders found in', target);
    process.exitCode = 1;
  }
}
