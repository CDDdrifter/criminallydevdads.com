/**
 * themePresets.ts — built-in Theme Studio palettes.
 *
 * Each preset is a complete colour swap (and background tint) that admin can
 * apply with one click from the Theme Studio tab. The studio merges these
 * into the current `ThemeConfig` (preserving non-colour fields and any
 * custom CSS / effects tweaks the admin already made).
 *
 * Authoring a new preset:
 *   1. Start from `defaultThemeColors()`.
 *   2. Tweak the tokens you want to override.
 *   3. Provide a 1-line description for the UI tile.
 *
 * Presets are intentionally stored as values (not derived from CSS rules)
 * so the studio can show a live colour-chip preview before the user applies.
 */

import type { ThemePreset } from '../types';
import { defaultThemeColors, defaultThemeBackgrounds } from './themeDefaults';

function preset(
  id: string,
  name: string,
  description: string,
  overrides: Partial<ThemePreset['theme']['colors']>,
  background?: Partial<ThemePreset['theme']['background']>,
): ThemePreset {
  const base = defaultThemeColors();
  const bg = defaultThemeBackgrounds();
  return {
    id,
    name,
    description,
    theme: {
      display_name: name,
      colors: { ...base, ...overrides },
      background: { ...bg, ...(background ?? {}) },
    },
  };
}

